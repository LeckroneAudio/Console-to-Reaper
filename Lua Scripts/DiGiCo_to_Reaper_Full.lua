-- record: optional {port=, tracks=} - inputs replaced by the Copy Audio record order
local function build_items(parsed, record)
    local items={}
    for _, sec in ipairs(SEC_ORDER) do
        local chs=parsed[sec] or {}
        local label=SEC_LABELS[sec]
        if sec=="inputs" and record then
            chs=record.tracks
            label="RECORD ORDER - "..record.port:upper().." (COPY AUDIO)"
        end
        if #chs>0 then
            items[#items+1]={type="header",sec=sec,label=label,count=#chs,color=COL[sec]}
            for _, ch in ipairs(chs) do
                items[#items+1]={type="channel",sec=sec,ch=ch,color=COL[sec],id=0}
            end
        end
    end
    for i,item in ipairs(items) do
        if item.type=="channel" then item.id=i end
    end
    return items
end

