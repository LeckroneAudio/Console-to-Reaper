local ok,filepath=reaper.GetUserFileNameForRead("","Select DiGiCo Show File (.ses or .rtf)","ses")
if not ok then return end

local is_ses=filepath:lower():match("%.ses$")~=nil
local f,err=io.open(filepath,is_ses and "rb" or "r")
if not f then
    reaper.ShowMessageBox("Could not open file:\n"..tostring(err),"DiGiCo to Reaper",0)
    return
end
local content=f:read("*all"); f:close()

if not content or content=="" then
    reaper.ShowMessageBox("File is empty.","DiGiCo to Reaper",0)
    return
end

local parsed
if is_ses then
    parsed=parse_ses(content)
    if not parsed then
        reaper.ShowMessageBox("Not a valid DiGiCo SD/Quantum show file (.ses).","DiGiCo to Reaper",0)
        return
    end
else
    parsed=parse_rtf(content)
end

local total=0
for _,sec in ipairs(SEC_ORDER) do total=total+#(parsed[sec] or {}) end
if total==0 then
    reaper.ShowMessageBox("No channels found in this file.","DiGiCo to Reaper",0)
    return
end

local filename=filepath:match("([^/\\]+)$") or filepath

-- Copy Audio record order (.ses only); falls back to channel order with a note
local copy = nil
if is_ses then
    local note, none
    copy, note, none = read_copy_audio(filepath)
    if none then
        copy = {ports={}, tracks={}, warnings={}, none=true}   -- read fine, no Copy Audio patch
    elseif not copy and note then
        filename = filename.."   (channel order: "..note..")"
    end
end
run_ui(parsed, filename, copy)
