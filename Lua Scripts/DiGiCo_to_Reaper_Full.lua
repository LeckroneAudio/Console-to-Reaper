    else                     fill(x,y,w,h,50, 50, 54) end
    gc(170,170,175); gfx.rect(x,y,w,h,0)
    gfx.setfont(1,"Arial",12)
    local tw,th = gfx.measurestr(label)
    gc(220,220,226)
