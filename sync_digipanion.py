#!/usr/bin/env python3
"""Regenerate digipanion_bundle.py from the DiGiPanion session parser.

The parser (digipanion-parser/digipanion-parse.mjs, from pandabearaudio.com)
reads the Copy Audio patch out of a DiGiCo .ses file. It's used unmodified:
this script drops the two Node imports and the command-line wrapper at the
end, wraps what's left so it defines window.digipanionParseSession, and
stores it as a Python string. The app serves that string to the browser at
/digipanion.js, so the parser runs in the page - no Node needed, and the
py2app / PyInstaller / Render builds pick it up through a normal import.

It also builds the Copy Audio helper embedded in the Reaper Lua scripts
(DiGiCo_to_Reaper_Full.lua, DiGiCo_Copy_Audio_to_Reaper.lua): copy_audio_runner.js + the parser +
the page's record-order functions from console_to_reaper.py, so Reaper and
the app always lay tracks out the same way.

Run this after replacing the digipanion-parser folder with a new version,
or after changing the record-order code in console_to_reaper.py.

Usage:  python3 sync_digipanion.py
"""

import hashlib
import re
import sys

SOURCE = 'digipanion-parser/digipanion-parse.mjs'
LICENSE = 'digipanion-parser/LICENSE'   # MIT: this notice must travel with every copy
BUNDLE = 'digipanion_bundle.py'
CLI_START = 'const filePath = process.argv[2];'
APP = 'console_to_reaper.py'
RUNNER = 'copy_audio_runner.js'
LUA_SCRIPTS = ['Lua Scripts/DiGiCo_to_Reaper_Full.lua',
               'Lua Scripts/DiGiCo_Copy_Audio_to_Reaper.lua']
LUA = LUA_SCRIPTS[0]
LUA_OPEN = 'local COPY_AUDIO_JS = [=====['
LUA_CLOSE = ']=====]'


def build_js(src):
    """Browser version of the parser: no Node imports, no CLI wrapper."""
    if CLI_START not in src:
        sys.exit(f'ERROR: "{CLI_START}" not found in {SOURCE} - the CLI wrapper '
                 'changed, update this script to match.')
    body = src[:src.index(CLI_START)]
    body = re.sub(r'^import [^\n]* from "node:[^"]+";\n', '', body, flags=re.M)
    if 'function parseSession(' not in body:
        sys.exit(f'ERROR: parseSession() not found in {SOURCE}')
    if re.search(r'\b(readFileSync|basename|process)\b', body):
        sys.exit(f'ERROR: {SOURCE} still uses Node APIs outside the CLI wrapper.')
    notice = ''.join('// ' + line if line.strip() else '//\n'
                     for line in open(LICENSE, encoding='utf-8').read().splitlines(keepends=True))
    return ('// DiGiPanion session parser by HoboTraveler (pandabearaudio.com),\n'
            '// https://github.com/HoboTraveler/DiGiPanionPatches - generated by sync_digipanion.py\n'
            '//\n' + notice + '\n'
            '(function () {\n' + body +
            'window.digipanionParseSession = parseSession;\n})();\n')


def record_order_js():
    """The page's record-order functions, unescaped the same way serve_html's
    string is, so the Lua helper runs exactly what the browser runs."""
    app = open(APP, encoding='utf-8').read()
    start = app.index('        function copyLabelParts(label) {')
    end = app.index('        function setupRecordOrder(data, session) {')
    return eval("'''" + app[start:end] + "'''")


def build_lua_helper(js):
    runner = open(RUNNER, encoding='utf-8').read()
    head, tail = runner.split('//@@RUN@@\n')
    return head + js + record_order_js() + tail


def sync_lua(js):
    helper = build_lua_helper(js)
    if LUA_CLOSE in helper:
        sys.exit(f'ERROR: the helper contains "{LUA_CLOSE}" which would end the Lua long string.')
    for script in LUA_SCRIPTS:
        sync_lua_script(script, helper)


def sync_lua_script(LUA, helper):
    lua = open(LUA, encoding='utf-8').read()
    i = lua.find(LUA_OPEN)
    if i < 0:
        sys.exit(f'ERROR: {LUA_OPEN} block not found in {LUA}')
    j = lua.index(LUA_CLOSE, i)
    new_lua = lua[:i] + LUA_OPEN + '\n' + helper + LUA_CLOSE + lua[j + len(LUA_CLOSE):]
    if new_lua == lua:
        print(f'{LUA}: already in sync')
        return
    open(LUA, 'w', encoding='utf-8').write(new_lua)
    print(f'synced Copy Audio helper ({len(helper)} bytes) into {LUA}')


def main():
    src = open(SOURCE, encoding='utf-8').read()
    js = build_js(src)
    sync_lua(js)
    digest = hashlib.sha256(src.encode('utf-8')).hexdigest()
    out = ('"""GENERATED by sync_digipanion.py - do not edit.\n\n'
           f'Browser build of {SOURCE}.\n"""\n\n'
           f'SOURCE_SHA256 = {digest!r}\n\n'
           f'DIGIPANION_JS = {js!r}\n')
    try:
        old = open(BUNDLE, encoding='utf-8').read()
    except FileNotFoundError:
        old = None
    if out == old:
        print('already in sync')
        return
    open(BUNDLE, 'w', encoding='utf-8').write(out)
    print(f'wrote {BUNDLE} ({len(js)} bytes of JS from {SOURCE})')


if __name__ == '__main__':
    main()
